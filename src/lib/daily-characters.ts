export function getDailyCharacter(dayOfYearIndex: number): DailyCharacter & { index: number } {
	const count = DAILY_CHARACTERS.length;
	const index = ((dayOfYearIndex % count) + count) % count;
	return { ...DAILY_CHARACTERS[index], index };
}
