export function getDailyColor(dayOfYearIndex: number): TraditionalColor & { index: number } {
	const count = TRADITIONAL_COLORS.length;
	const index = ((dayOfYearIndex % count) + count) % count;
	return { ...TRADITIONAL_COLORS[index], index };
}
